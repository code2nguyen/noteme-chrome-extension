// Writes src/c2n-theme.generated.css: the part of the c2n base theme (@c2n/theme/base.css) Noteme needs.
//
// The base theme maps the CSS variables of every c2 component onto the theme tokens: about 3,400 declarations on
// :root for 140 components, 260 KB that every new tab would parse. Noteme uses some forty of them. This keeps the
// section of each component whose variables the app can read, and drops the others.
//
//   node scripts/theme-subset.ts            -> writes the file (after adding a c2 component or upgrading c2n)
//   node scripts/theme-subset.ts --check    -> fails when the file is not up to date (CI)
//
// A section is kept when one of its variables is named in code the app loads: every module reachable from
// src/main.ts (esbuild follows the imports, lazy routes included) and Noteme's own templates and stylesheets. A
// variable is matched by its whole name, so nothing a component reads can lose its mapping.

import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'src/c2n-theme.generated.css');
const require = createRequire(import.meta.url);

/** The base theme, as its header and one block per component (`/* @c2n/<name> *\/` then its rules). */
export function splitTheme(css: string): { head: string; sections: { name: string; css: string }[]; tail: string } {
  const parts = css.split(/\n(?= {2}\/\* @c2n\/[a-z0-9-]+ \*\/\n)/);
  const head = parts.shift() ?? '';
  const last = parts.pop() ?? '';
  // The layer's closing brace follows the last section.
  const end = last.lastIndexOf('\n}');
  parts.push(last.slice(0, end));
  return {
    head,
    sections: parts.map((part) => ({ name: /\/\* (@c2n\/[a-z0-9-]+) \*\//.exec(part)![1], css: part })),
    tail: last.slice(end),
  };
}

/** The variables a section declares. */
export function declared(section: string): string[] {
  return [...section.matchAll(/^\s*(--c2-[a-z0-9_-]+)\s*:/gm)].map((match) => match[1]);
}

/** The sections with a variable that `code` names, whole (`--c2-list` is not `--c2-list-item`). */
export function neededSections<T extends { css: string }>(sections: T[], code: string): T[] {
  const named = new Set(code.match(/--c2-[a-z0-9_-]+/g) ?? []);
  return sections.filter((section) => declared(section.css).some((name) => named.has(name)));
}

function files(directory: string, extensions: RegExp): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path, extensions) : extensions.test(entry.name) ? [path] : [];
  });
}

/** Everything the app loads, as text: its modules and their dependencies, and its templates and stylesheets. */
async function loadedCode(): Promise<string> {
  const result = await build({
    entryPoints: [resolve(root, 'src/main.ts')],
    bundle: true,
    write: false,
    metafile: true,
    format: 'esm',
    splitting: true,
    outdir: 'out',
    platform: 'browser',
    tsconfig: resolve(root, 'tsconfig.app.json'),
    logLevel: 'silent',
  });
  const modules = Object.keys(result.metafile.inputs).map((path) => resolve(root, path));
  const own = files(resolve(root, 'src'), /\.(html|scss)$/);
  return [...modules, ...own].map((path) => readFileSync(path, 'utf8')).join('\n');
}

export async function themeSubset(): Promise<string> {
  const source = require.resolve('@c2n/theme/base.css');
  const { head, sections, tail } = splitTheme(readFileSync(source, 'utf8'));
  const kept = neededSections(sections, await loadedCode());
  const note = [
    '/*',
    ' * GENERATED by scripts/theme-subset.ts (npm run theme). Do not edit by hand.',
    ` * The c2n base theme for the ${kept.length} components Noteme uses, of the ${sections.length} in`,
    ` * ${relative(root, source)
      .replace(/\\/g, '/')
      .replace(/^node_modules\//, '')}.`,
    ' */',
  ].join('\n');
  return `${note}\n${head}\n${kept.map((section) => section.css).join('\n')}${tail}`.trimEnd() + '\n';
}

if (import.meta.main) {
  const css = await themeSubset();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // Missing reads as out of date.
    }
    if (current !== css) {
      console.error('src/c2n-theme.generated.css is not up to date: run npm run theme and commit the result');
      process.exit(1);
    }
  } else {
    writeFileSync(target, css);
    console.log(`${relative(root, target)}: ${(css.length / 1024).toFixed(0)} KB`);
  }
}
